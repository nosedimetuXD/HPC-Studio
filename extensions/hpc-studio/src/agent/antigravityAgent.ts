import * as vscode from 'vscode';
import * as cp from 'child_process';
import * as fs from 'fs';
import * as path from 'path';

export class AntigravityAgentBridge implements vscode.Disposable {
	private readonly _sessionConversations = new Map<string, string>();
	private _activeProcesses = new Map<string, cp.ChildProcess>();

	constructor() {}

	public dispose(): void {
		for (const proc of this._activeProcesses.values()) {
			try {
				proc.kill('SIGTERM');
			} catch {
				// ignore
			}
		}
		this._activeProcesses.clear();
		this._sessionConversations.clear();
	}

	private _resolveAgyPath(): string {
		const config = vscode.workspace.getConfiguration('hpc-studio');
		const configuredPath = config.get<string>('antigravityPath');
		if (configuredPath && fs.existsSync(configuredPath)) {
			return configuredPath;
		}

		const homeDir = process.env.HOME || process.env.USERPROFILE || '';
		const localBinAgy = path.join(homeDir, '.local', 'bin', 'agy');
		if (fs.existsSync(localBinAgy)) {
			return localBinAgy;
		}

		return 'agy';
	}

	public async invoke(
		prompt: string,
		sessionId?: string,
		workingDir?: string
	): Promise<string> {
		const agyPath = this._resolveAgyPath();
		const cwd =
			workingDir ||
			vscode.workspace.workspaceFolders?.[0]?.uri.fsPath ||
			process.cwd();

		const args = ['-p', prompt, '--output-format', 'json'];

		if (sessionId && this._sessionConversations.has(sessionId)) {
			const conversationId = this._sessionConversations.get(sessionId)!;
			args.push('--conversation', conversationId);
		}

		return new Promise<string>((resolve, reject) => {
			let proc: cp.ChildProcess;
			try {
				proc = cp.spawn(agyPath, args, {
					cwd,
					env: { ...process.env, PAGER: 'cat' },
				});
			} catch (err: unknown) {
				const msg = err instanceof Error ? err.message : String(err);
				return reject(new Error(`Failed to spawn Antigravity CLI (${agyPath}): ${msg}`));
			}

			if (sessionId) {
				this._activeProcesses.set(sessionId, proc);
			}

			let stdout = '';
			let stderr = '';

			proc.stdout?.on('data', (chunk) => {
				stdout += chunk.toString();
			});

			proc.stderr?.on('data', (chunk) => {
				stderr += chunk.toString();
			});

			proc.on('error', (err) => {
				if (sessionId) {
					this._activeProcesses.delete(sessionId);
				}
				reject(new Error(`Antigravity execution failed: ${err.message}`));
			});

			proc.on('close', (code) => {
				if (sessionId) {
					this._activeProcesses.delete(sessionId);
				}

				if (code !== 0 && !stdout.trim()) {
					const errorMsg = stderr.trim() || `Antigravity CLI exited with code ${code}`;
					return reject(new Error(errorMsg));
				}

				try {
					const parsed = JSON.parse(stdout.trim());
					if (parsed.conversation_id && sessionId) {
						this._sessionConversations.set(sessionId, parsed.conversation_id);
					}
					if (typeof parsed.response === 'string') {
						return resolve(parsed.response.trim());
					}
				} catch {
					// If stdout was not pure JSON, fall back to plain text
				}

				if (stdout.trim()) {
					resolve(stdout.trim());
				} else {
					resolve(stderr.trim() || 'No response generated by Antigravity.');
				}
			});
		});
	}
}
